from datasets import load_dataset

# Load a dataset from Hugging Face. Here we use 'mnist' as an example.
dataset = load_dataset('dralsarrani/prompt_safety_with_synthetic')

# Display the dataset structure
print(dataset)

import pandas as pd

# Assuming 'dataset' is already loaded and contains 'train' and 'test' splits

# Convert the training split to a pandas DataFrame
train_df = dataset['train'].to_pandas()
print("Train DataFrame head:")
print(train_df.head())

# Convert the test split to a pandas DataFrame
test_df = dataset['test'].to_pandas()
print("\nTest DataFrame head:")
print(test_df.head())

# Map 1.0 to 'unsafe' and 0.0 to 'safe' in the 'label' column of train_df
train_df['label'] = train_df['label'].replace({1.0: 'unsafe', 0.0: 'safe'})

# Map 1.0 to 'unsafe' and 0.0 to 'safe' in the 'label' column of test_df
test_df['label'] = test_df['label'].replace({1.0: 'unsafe', 0.0: 'safe'})

print("Updated Train DataFrame head:")
print(train_df.head())

print("\nUpdated Test DataFrame head:")
print(test_df.head())

from huggingface_hub import notebook_login

notebook_login()

from datasets import Dataset, DatasetDict

# Convert pandas DataFrames back to Dataset objects
train_dataset = Dataset.from_pandas(train_df)
test_dataset = Dataset.from_pandas(test_df)

# Create a DatasetDict
hf_dataset = DatasetDict({
    'train': train_dataset,
    'test': test_dataset
})

repo_id = 'dralsarrani/prompt_safety_with_synthetic_labeled'

# Push the dataset
hf_dataset.push_to_hub(repo_id)

print(f"Dataset successfully uploaded to: https://huggingface.co/datasets/{repo_id}")

