import re

def clean_prompt(prompt):
    # Ensure prompt is a string
    if not isinstance(prompt, str):
        return prompt # Return as is if not a string

    # Remove everything before the first colon
    if ':' in prompt:
        prompt = prompt.split(':', 1)[1].strip()

    # Remove any text between square brackets []
    prompt = re.sub(r'\[.*?\]', '', prompt)

    # Remove emojis (a broad range of Unicode characters)
    # This regex attempts to match a wide range of emoji Unicode blocks
    emoji_pattern = re.compile(
        "["
        "\U0001F600-\U0001F64F"  # emoticons
        "\U0001F300-\U0001F5FF"  # symbols & pictographs
        "\U0001F680-\U0001F6FF"  # transport & map symbols
        "\U0001F700-\U0001F77F"  # alchemical symbols
        "\U0001F780-\U0001F7FF"  # Geometric Shapes Extended
        "\U0001F800-\U0001F8FF"  # Supplemental Arrows-C
        "\U0001F900-\U0001F9FF"  # Supplemental Symbols and Pictographs
        "\U0001FA00-\U0001FA6F"  # Chess Symbols
        "\U0001FA70-\U0001FAFF"  # Symbols and Pictographs Extended-A
        "\U00002702-\U000027B0"  # Dingbats
        "\U000024C2-\U0001F251"
        "]+", flags=re.UNICODE)
    prompt = emoji_pattern.sub(r'', prompt)

    return prompt

